const contractsRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

async function canonicalSources() {
  return Promise.all([
    readFile(desktopContractPaths.manifest),
    readFile(desktopContractPaths.fixtures),
    readFile(desktopContractPaths.policy),
  ]);
}

test('Rust handler/constants and TypeScript literals are derived byte-for-byte from one manifest', async () => {
  const sources = await canonicalSources();
  const rendered = renderDesktopBindings(...sources);
  const manifest = JSON.parse(sources[0].toString('utf8'));
  const [rustContract, rustHandler, typescript] = await Promise.all([
    readFile(desktopContractPaths.rustContract, 'utf8'),
    readFile(desktopContractPaths.rustHandler, 'utf8'),
    readFile(desktopContractPaths.typescript, 'utf8'),
  ]);
  assert.equal(rustContract, rendered.rustContract);
  assert.equal(rustHandler, rendered.rustHandler);
  assert.equal(typescript, rendered.typescript);
  assert.match(rustContract, /\("interruptTurn", "runtime_turn_interrupt"\)/u);
  assert.match(rustContract, /\("steerTurn", "runtime_turn_steer"\)/u);
  assert.match(rustContract, /\("stageAttachmentBytes", "raw_octet_stream", "json_envelope"\)/u);
  assert.match(rustContract, /\("readAttachmentPreview", "json_envelope", "raw_octet_stream"\)/u);
  assert.match(rustContract, /GENERATED_VOICE_TRANSCRIPT_MAX_UTF8_BYTES: usize = 65536/u);
  assert.match(rustContract, /GENERATED_ATTACHMENT_MAX_PER_DISPATCH: usize = 4/u);
  assert.match(rustContract, /\("\.tsx", "text", "text\/typescript"\)/u);
  assert.match(rustHandler, /commands::runtime_turn_interrupt/u);
  assert.match(rustHandler, /commands::runtime_turn_steer/u);
  assert.equal(
    [...rustHandler.matchAll(/commands::[a-z][a-z0-9_]*/gu)].length,
    Object.keys(manifest.commands).length,
  );
  assert.match(typescript, /export type NativeCommandName = keyof typeof NATIVE_COMMANDS/u);
  assert.match(typescript, /export const NATIVE_BINARY_TRANSPORTS/u);
  assert.match(typescript, /export const NATIVE_CONTENT_POLICY/u);
  assert.match(typescript, /export const NATIVE_ATTACHMENT_PICKER_ACCEPT/u);
  assert.match(typescript, /export type NativeEventName = keyof typeof NATIVE_EVENTS/u);
});

test('content policy rejects ambiguous formats and limits that could create unsendable drafts', async () => {
  const [manifestBytes, fixtureBytes, policyBytes] = await canonicalSources();
  const canonical = JSON.parse(manifestBytes.toString('utf8'));
  const render = (operation, expected) => {
    const manifest = structuredClone(canonical);
    operation(manifest.contentPolicy);
    assert.throws(
      () => renderDesktopBindings(Buffer.from(JSON.stringify(manifest)), fixtureBytes, policyBytes),
      expected,
    );
  };
  render((contentPolicy) => {
    contentPolicy.voice.transcriptMaxUtf8Bytes = contentPolicy.message.maxUtf8Bytes + 1;
  }, /desktop_content_policy_text_invalid/u);
  render((contentPolicy) => {
    contentPolicy.attachments.formats.push(structuredClone(contentPolicy.attachments.formats[0]));
  }, /desktop_content_policy_attachment_format_invalid/u);
  render((contentPolicy) => {
    contentPolicy.attachments.formats[0].kind = 'text';
  }, /desktop_content_policy_attachment_format_invalid/u);
  render((contentPolicy) => {
    contentPolicy.attachments.maxTextBytesPerDispatch = contentPolicy.attachments.maxTextBytes - 1;
  }, /desktop_content_policy_attachment_limits_invalid/u);
});

