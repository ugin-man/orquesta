test('binary transport exceptions and every command fixture fail closed on shape or body-mode drift', async () => {
  const [manifestBytes, fixtureBytes, policyBytes] = await canonicalSources();
  const canonicalManifest = JSON.parse(manifestBytes.toString('utf8'));
  const canonicalFixtures = JSON.parse(fixtureBytes.toString('utf8'));
  const render = (mutateManifest, mutateFixtures, expected) => {
    const manifest = structuredClone(canonicalManifest);
    const fixtures = structuredClone(canonicalFixtures);
    mutateManifest?.(manifest);
    mutateFixtures?.(fixtures);
    assert.throws(
      () => renderDesktopBindings(
        Buffer.from(JSON.stringify(manifest)),
        Buffer.from(JSON.stringify(fixtures)),
        policyBytes,
      ),
      expected,
    );
  };

  render((manifest) => {
    manifest.binaryTransports.unknown = { request: 'raw_octet_stream', response: 'json_envelope' };
  }, null, /desktop_bridge_binary_transport_command_unknown/u);
  render((manifest) => {
    manifest.binaryTransports.stageAttachmentBytes.extra = true;
  }, null, /desktop_bridge_binary_transport_invalid/u);
  render((manifest) => {
    delete manifest.binaryTransports.stageAttachmentBytes.response;
  }, null, /desktop_bridge_binary_transport_invalid/u);
  render((manifest) => {
    manifest.binaryTransports.stageAttachmentBytes.request = 'bytes_maybe';
  }, null, /desktop_bridge_binary_transport_mode_invalid/u);
  render((manifest) => {
    manifest.binaryTransports.stageAttachmentBytes = { request: 'json_envelope', response: 'json_envelope' };
  }, null, /desktop_bridge_binary_transport_redundant/u);
  render(null, (fixtures) => {
    fixtures.commands.runtimeCall.args = {
      rawHeaders: {}, rawBodyBase64: '',
    };
  }, /desktop_bridge_json_fixture_request_invalid/u);
  render(null, (fixtures) => {
    fixtures.commands.runtimeCall.args.extra = true;
  }, /desktop_bridge_json_fixture_request_invalid/u);
  render(null, (fixtures) => {
    fixtures.commands.runtimeCall.response.extra = true;
  }, /desktop_bridge_json_fixture_response_invalid/u);
  render(null, (fixtures) => {
    fixtures.commands.stageAttachmentBytes.args = {
      input: { schemaVersion: 1 },
    };
  }, /desktop_bridge_binary_fixture_request_invalid/u);
  render(null, (fixtures) => {
    fixtures.commands.readAttachmentPreview.response = {
      schemaVersion: 1, result: null,
    };
  }, /desktop_bridge_binary_fixture_response_invalid/u);
});

