test('generator and runtime share an exact fail-closed method-policy validator', async () => {
  const [manifestBytes, fixtureBytes, policyBytes] = await canonicalSources();
  const canonical = JSON.parse(policyBytes.toString('utf8'));
  const mutate = (operation) => {
    const policy = structuredClone(canonical);
    operation(policy);
    return policy;
  };
  const cases = [
    ['root shape', mutate((policy) => { policy.rogue = true; }), /runtime_method_policy_shape_invalid/u],
    ['entry shape', mutate((policy) => { policy.methods['runtime.info'].rogue = true; }), /entry_shape_invalid/u],
    ['method name', mutate((policy) => {
      policy.methods['Runtime.info'] = policy.methods['runtime.info'];
      delete policy.methods['runtime.info'];
    }), /name_invalid/u],
    ['response', mutate((policy) => { policy.methods['runtime.info'].responseType = '   '; }), /response_invalid/u],
    ['boolean', mutate((policy) => { policy.methods['runtime.info'].rendererExposed = 'yes'; }), /boolean_invalid/u],
    ['mutation enum', mutate((policy) => { policy.methods['runtime.info'].mutationKind = 'other'; }), /enum_invalid/u],
    ['project enum', mutate((policy) => { policy.methods['runtime.info'].projectRequirement = 'other'; }), /enum_invalid/u],
    ['recovery enum', mutate((policy) => { policy.methods['runtime.info'].recoveryStrategy = 'other'; }), /enum_invalid/u],
    ['timeout', mutate((policy) => { policy.methods['runtime.info'].defaultTimeoutMs = 999; }), /timeout_invalid/u],
    ['recovery parity', mutate((policy) => { policy.methods['runtime.info'].recoveryStrategy = 'native_lifecycle'; }), /recovery_mismatch/u],
    ['attachments', mutate((policy) => { policy.methods['runtime.info'].attachmentsAllowed = true; }), /attachment_mismatch/u],
    ['renderer unavailable', mutate((policy) => { policy.methods['repository.get-snapshot'].recoveryStrategy = 'internal_unavailable'; }), /unavailable_exposed/u],
    ['runtime.send', mutate((policy) => { policy.methods['runtime.send'].responseType = 'other'; }), /runtime_send_must_be_typed_native_dispatch/u],
  ];
  for (const [label, policy, expected] of cases) {
    assert.throws(() => validateMethodPolicy(policy), expected, label);
    assert.throws(
      () => renderDesktopBindings(manifestBytes, fixtureBytes, Buffer.from(JSON.stringify(policy))),
      expected,
      `generator: ${label}`,
    );
  }
});

test('validated method policy is a detached deeply frozen authority', async () => {
  const [, , policyBytes] = await canonicalSources();
  const input = JSON.parse(policyBytes.toString('utf8'));
  const validated = validateMethodPolicy(input);
  const originalTimeout = validated.methods['runtime.send'].defaultTimeoutMs;

  assert.notEqual(validated, input);
  assert.notEqual(validated.methods, input.methods);
  assert.equal(Object.isFrozen(validated), true);
  assert.equal(Object.isFrozen(validated.methods), true);
  for (const entry of Object.values(validated.methods)) assert.equal(Object.isFrozen(entry), true);

  input.methods['runtime.send'].defaultTimeoutMs = 1;
  assert.equal(validated.methods['runtime.send'].defaultTimeoutMs, originalTimeout);
});

